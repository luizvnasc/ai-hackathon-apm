#!/usr/bin/env python3
"""Copy shared/*.py into the skills that import them (stdlib only).

    python3 tools/sync_shared.py          # write the copies
    python3 tools/sync_shared.py --check  # exit 1 when a copy differs

APM installs each skill folder by itself, so shared code has to be inside every one. A skill gets the
modules its scripts import with `from hackathon_shared.<module> import ...`, and the modules those import
(`from .<module> import ...`), as generated files in scripts/hackathon_shared/. Edit only shared/.
"""
import argparse
import ast
import pathlib
import sys

PACKAGE = "hackathon_shared"
MARK = "# GENERATED by tools/sync_shared.py"


def imported(script):
    """The shared modules a script imports."""
    return {n.module.split(".", 1)[1] for n in ast.walk(ast.parse(script.read_text(encoding="utf-8")))
            if isinstance(n, ast.ImportFrom) and (n.module or "").startswith(PACKAGE + ".")}


def dependencies(source):
    """The shared modules a shared module imports."""
    names = set()
    for node in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
        if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
            names.add(node.module)
    return names


def needed_modules(root, scripts_dir):
    """What the scripts import, followed through the imports between shared modules."""
    pending = set()
    for script in sorted(scripts_dir.glob("*.py")):
        pending |= imported(script)
    needed = set()
    while pending:
        name = pending.pop()
        source = root / "shared" / f"{name}.py"
        if not source.is_file():
            sys.exit(f"{scripts_dir}: imports {PACKAGE}.{name}, but shared/{name}.py does not exist")
        needed.add(name)
        pending |= dependencies(source) - needed
    return needed


def expected(root, scripts_dir):
    """{file name: content} of one skill's generated package."""
    modules = needed_modules(root, scripts_dir)
    if not modules:
        return {}
    files = {"__init__.py": f"{MARK}: edit shared/, not this package.\n"}
    for name in sorted(modules):
        source = root / "shared" / f"{name}.py"
        files[f"{name}.py"] = f"{MARK} from shared/{name}.py: edit that file.\n" + source.read_text(encoding="utf-8")
    return files


def sync(root, write):
    """The problems found. With write, fixes them and returns only what it could not fix."""
    problems = []
    for scripts_dir in sorted((root / ".apm" / "skills").glob("*/scripts")):
        package, wanted = scripts_dir / PACKAGE, expected(root, scripts_dir)
        for name, content in wanted.items():
            path = package / name
            # read_text translates CRLF, so a Windows checkout is not drift
            if path.is_file() and path.read_text(encoding="utf-8") == content:
                continue
            if write:
                package.mkdir(exist_ok=True)
                path.write_bytes(content.encode("utf-8"))
            else:
                problems.append(f"out of date: {path.relative_to(root)}")
        for path in sorted(package.glob("*.py")):
            if path.name in wanted:
                continue
            if not path.read_text(encoding="utf-8").startswith(MARK):
                problems.append(f"not generated, move it out: {path.relative_to(root)}")
            elif write:
                path.unlink()
            else:
                problems.append(f"no longer used: {path.relative_to(root)}")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing, fail on drift")
    a = ap.parse_args(argv)
    problems = sync(pathlib.Path(__file__).resolve().parents[1], write=not a.check)
    print("\n".join(problems) if problems else "shared modules in sync")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
